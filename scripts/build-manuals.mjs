import {cp,mkdir,readdir,rm,writeFile} from 'node:fs/promises';
import path from 'node:path';
export async function buildManuals(root){
  const source=path.join(root,'manuals'),target=path.join(root,'dist/manuals');
  await mkdir(path.dirname(target),{recursive:true});
  await rm(target,{recursive:true,force:true});
  await cp(source,target,{recursive:true});
  const paths=[];
  async function walk(dir){
    for(const e of await readdir(dir,{withFileTypes:true})){
      const p=path.join(dir,e.name);
      if(e.isDirectory())await walk(p);
      else if(e.isFile()){
        const route='/manuals/'+path.relative(target,p).split(path.sep).join('/');
        paths.push(route);
        if(route.endsWith('.html'))paths.push(route.slice(0,-5));
      }else throw Error('Manuals must contain regular files only');
    }
  }
  await walk(target);paths.push('/manuals','/manuals/');
  const csp="default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src 'self' data:; base-uri 'none'; form-action 'none'; frame-ancestors 'none'";
  await writeFile(path.join(root,'manual-paths.mjs'),'// Generated by scripts/build-manuals.mjs. Exact published book and practice paths.\nexport const MANUAL_CSP='+JSON.stringify(csp)+';\nexport const MANUAL_PATHS=new Set('+JSON.stringify([...new Set(paths)].sort(),null,2)+');\n');
}
